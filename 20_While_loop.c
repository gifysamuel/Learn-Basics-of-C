# include <stdio.h>


    // While Loop = A while loop is a loop that continues running while its condition evaluates to true. It checks the condition before each iteration.

int main () {

    int num = 0;
    
    while (num <= 0) {
        printf("Enter a number wich is greater than 0 : ");
        scanf("%d",&num);
    }
    
return 0;
}